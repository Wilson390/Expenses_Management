CREATE TABLE IF NOT EXISTS pastor (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(150) NOT NULL,
 mobile_no VARCHAR(20) NOT NULL UNIQUE,
 email VARCHAR(180), dob DATE, doj DATE, dor DATE,
 gender VARCHAR(20), active BOOLEAN NOT NULL DEFAULT TRUE,
 profile_pic VARCHAR(500), created_at TIMESTAMP WITH TIME ZONE,
 updated_at TIMESTAMP WITH TIME ZONE, created_by VARCHAR(120), updated_by VARCHAR(120)
);
